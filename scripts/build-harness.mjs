// Compiles harness/**/*.mts, scripts/**/*.mts, apps/docs/scripts/**/*.mts and the Claude hooks (.claude/hooks, .claude/skills/*/hooks) in place (x.mts -> x.mjs, so every `import './x.mjs'` keeps working)
// and lists each output in a .gitignore beside its tree, so a hand-written .mjs is never ignored by accident.
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, rmSync, statSync, utimesSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE_ROOTS = ['harness', 'scripts', 'apps/docs/scripts', '.claude'];
const SKIP = ['harness/templates/', 'harness/catalog/'];

// Not harness/lib/files.mjs: this script compiles that module, so it cannot depend on it.
function walk(root, rel) {
  if (!existsSync(path.join(root, rel))) return [];
  return readdirSync(path.join(root, rel), { withFileTypes: true }).flatMap((e) => {
    const next = path.join(rel, e.name);
    if (e.isDirectory()) return e.name === 'node_modules' || e.name.startsWith('.') ? [] : walk(root, next);
    return e.isFile() ? [next] : [];
  });
}

// Under .claude only the hook folders: the rest is Markdown, and .claude/worktrees holds whole other checkouts.
function sources(root, base) {
  if (base !== '.claude') return walk(root, base);
  const skills = path.join(root, '.claude/skills');
  const skillHooks = existsSync(skills) ? readdirSync(skills, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => `.claude/skills/${e.name}/hooks`) : [];
  return ['.claude/hooks', ...skillHooks].flatMap((d) => walk(root, d));
}

// Projects import harness/* (#harness/*), so its modules also ship their declarations for the project's TypeScript.
const DECLARED = new Set(['harness']);

export function compiledOutputs(root, base) {
  return sources(root, base)
    .sort()
    .filter((f) => f.endsWith('.mts') && !f.endsWith('.d.mts') && !SKIP.some((s) => f.startsWith(s)))
    .flatMap((f) => {
      const out = `/${path.relative(base, f).replace(/\.mts$/, '')}`;
      return DECLARED.has(base) ? [`${out}.mjs`, `${out}.d.mts`] : [`${out}.mjs`];
    });
}

const header = '# GENERATED by scripts/build-harness.mjs: the compiled output of each .mts beside it. Do not edit.\n';

export function writeIgnoreFiles(root) {
  const written = [];
  for (const base of SOURCE_ROOTS) {
    const file = path.join(root, base, '.gitignore');
    const outputs = compiledOutputs(root, base);
    // An output listed last time whose .mts is gone (renamed or deleted) would otherwise stay on disk, untracked yet packed
    // and hashed; only a list this script wrote is trusted.
    const previous = existsSync(file) ? readFileSync(file, 'utf8') : '';
    if (previous.startsWith(header)) {
      for (const out of previous.split('\n').filter((l) => l.startsWith('/') && !outputs.includes(l))) rmSync(path.join(root, base, out), { force: true });
    }
    if (!outputs.length) {
      if (existsSync(file)) rmSync(file);
      continue;
    }
    const next = header + outputs.join('\n') + '\n';
    if (!existsSync(file) || readFileSync(file, 'utf8') !== next) writeFileSync(file, next);
    written.push(file);
  }
  return written;
}

// tsc emits into a cache folder (it also emits the hand-written .mjs an .mts imports, which must not be overwritten in
// place); only the output of each .mts is copied next to its source.
const CACHE = 'node_modules/.cache/harness-build';
const BUILD_INFO = 'node_modules/.cache/tsconfig.harness.tsbuildinfo';

export function compile(root) {
  const tsc = createRequire(import.meta.url).resolve('typescript/bin/tsc');
  const run = () => execFileSync(process.execPath, [tsc, '-p', path.join(root, 'tsconfig.harness.json')], { cwd: root, stdio: 'inherit' });
  const outputs = SOURCE_ROOTS.flatMap((base) => compiledOutputs(root, base).map((out) => path.join(base, out)));
  run();
  // An incremental build skips files it believes are emitted; a cleared cache folder must not leave them missing.
  if (outputs.some((out) => !existsSync(path.join(root, CACHE, out)))) {
    rmSync(path.join(root, BUILD_INFO), { force: true });
    run();
  }
  for (const out of outputs) {
    const from = path.join(root, CACHE, out);
    const to = path.join(root, out);
    if (!existsSync(to) || !readFileSync(to).equals(readFileSync(from))) {
      mkdirSync(path.dirname(to), { recursive: true });
      copyFileSync(from, to);
    }
    // The hook launcher compares source/output mtimes. A touched source or a
    // clock skew can leave identical (or freshly copied) output older, causing
    // every hook invocation to rebuild indefinitely.
    if (to.endsWith('.mjs')) {
      const source = to.slice(0, -4) + '.mts';
      const sourceTime = statSync(source).mtime;
      const outputTime = statSync(to);
      if (sourceTime > outputTime.mtime) utimesSync(to, outputTime.atime, sourceTime);
    }
  }
}

// Compared as real paths: a URL built from argv by hand misses a path with a space (%20) or a symlink.
if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  const written = writeIgnoreFiles(ROOT);
  if (written.length) compile(ROOT);
  console.log(`[build:harness] ${SOURCE_ROOTS.reduce((n, b) => n + compiledOutputs(ROOT, b).filter((f) => f.endsWith('.mjs')).length, 0)} module(s) compiled in place`);
}
